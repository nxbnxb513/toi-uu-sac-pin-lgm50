function [Ulith, Udelith, dUdT] = dfn_ocp_neg(x)
%DFN_OCP_NEG (BAN CHAN DOAN, chi dung trong bien the 'ocp_end' cua diag_variant)
% = Li 2025 SI (S3), (S4), (S6) nhu src/dfn/dfn_ocp_neg.m, CONG them vao ca hai
% nhanh so hang (RT/F) ln((1-x)/(1-x+0.01)) o 25 C: ~0 khi x < 0.95, -> -inf khi
% x -> 1. KHONG phai tham so de xuat: chi de kiem tra gia thuyet "U_n khong co
% diem ky di o x = 1 nen hat phia mang ngan bi day tron ma khong bi day dong di".
Ulith = 0.5476*exp(-422.4*x) + 0.5705*exp(-36.89*x) + 0.1336 ...
      - 0.04758*tanh(13.88*(x - 0.2101)) ...
      - 0.01761*tanh(36.2*(x - 0.5639)) ...
      - 0.0169*tanh(11.42*(x - 1));
Udelith = 1.051*exp(-26.76*x) + 0.1916 ...
      - 0.05598*tanh(35.62*(x - 0.1356)) ...
      - 0.04483*tanh(14.64*(x - 0.2861)) ...
      - 0.02097*tanh(26.28*(x - 0.6183)) ...
      - 0.02398*tanh(38.1*(x - 1));
xe = min(x, 1 - 1e-12);
dU = 0.025693*log((1 - xe)./(1 - xe + 0.01));
Ulith = Ulith + dU; Udelith = Udelith + dU;
if nargout > 2
    dUdT = 1e-3*(-0.111*x + 0.02901 + 0.3562*exp(-(x - 0.08308).^2/0.004621));
end
end
